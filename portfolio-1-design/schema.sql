-- MivaLearn fictional university registration and results portal.
-- Target: PostgreSQL. Execute in a newly created, empty database.

CREATE TABLE department (
    department_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    department_code VARCHAR(12) NOT NULL UNIQUE,
    department_name VARCHAR(120) NOT NULL UNIQUE
);

CREATE TABLE student (
    student_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    matric_number VARCHAR(24) NOT NULL UNIQUE,
    first_name VARCHAR(80) NOT NULL,
    last_name VARCHAR(80) NOT NULL,
    email VARCHAR(254) NOT NULL UNIQUE,
    department_id BIGINT NOT NULL REFERENCES department(department_id),
    admission_year SMALLINT NOT NULL CHECK (admission_year BETWEEN 2000 AND 2100),
    status VARCHAR(12) NOT NULL DEFAULT 'active'
        CHECK (status IN ('active', 'suspended', 'graduated', 'withdrawn'))
);

CREATE TABLE course (
    course_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_code VARCHAR(16) NOT NULL UNIQUE,
    title VARCHAR(160) NOT NULL,
    credits SMALLINT NOT NULL CHECK (credits BETWEEN 1 AND 12),
    department_id BIGINT NOT NULL REFERENCES department(department_id)
);

CREATE TABLE academic_term (
    term_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    academic_year VARCHAR(9) NOT NULL,
    term_name VARCHAR(12) NOT NULL CHECK (term_name IN ('First', 'Second', 'Summer')),
    starts_on DATE NOT NULL,
    ends_on DATE NOT NULL,
    CHECK (ends_on > starts_on),
    UNIQUE (academic_year, term_name)
);

CREATE TABLE course_offering (
    offering_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT NOT NULL REFERENCES course(course_id),
    term_id BIGINT NOT NULL REFERENCES academic_term(term_id),
    section_code VARCHAR(12) NOT NULL,
    lecturer_name VARCHAR(160) NOT NULL,
    capacity INTEGER NOT NULL CHECK (capacity > 0),
    seats_remaining INTEGER NOT NULL,
    CHECK (seats_remaining BETWEEN 0 AND capacity),
    UNIQUE (course_id, term_id, section_code)
);

CREATE TABLE enrollment (
    enrollment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id BIGINT NOT NULL REFERENCES student(student_id),
    offering_id BIGINT NOT NULL REFERENCES course_offering(offering_id),
    registered_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    status VARCHAR(12) NOT NULL DEFAULT 'registered'
        CHECK (status IN ('registered', 'dropped', 'completed')),
    UNIQUE (student_id, offering_id)
);

CREATE TABLE assessment (
    assessment_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    offering_id BIGINT NOT NULL REFERENCES course_offering(offering_id),
    assessment_name VARCHAR(100) NOT NULL,
    max_score NUMERIC(6,2) NOT NULL CHECK (max_score > 0),
    weight_percent NUMERIC(5,2) NOT NULL CHECK (weight_percent > 0 AND weight_percent <= 100),
    UNIQUE (offering_id, assessment_name)
);

CREATE TABLE assessment_result (
    assessment_id BIGINT NOT NULL REFERENCES assessment(assessment_id),
    enrollment_id BIGINT NOT NULL REFERENCES enrollment(enrollment_id),
    score NUMERIC(6,2) NOT NULL CHECK (score >= 0),
    recorded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    recorded_by VARCHAR(120) NOT NULL,
    PRIMARY KEY (assessment_id, enrollment_id)
);

-- A row CHECK cannot compare a score with max_score stored in another table,
-- so enforce that cross-table business rule with a trigger.
CREATE FUNCTION enforce_assessment_max_score()
RETURNS TRIGGER
LANGUAGE plpgsql
AS $$
DECLARE
    v_max_score NUMERIC(6,2);
BEGIN
    SELECT max_score INTO v_max_score
    FROM assessment
    WHERE assessment_id = NEW.assessment_id;

    IF NEW.score > v_max_score THEN
        RAISE EXCEPTION 'score % exceeds assessment maximum %', NEW.score, v_max_score;
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER assessment_result_score_limit
BEFORE INSERT OR UPDATE OF score, assessment_id ON assessment_result
FOR EACH ROW EXECUTE FUNCTION enforce_assessment_max_score();

-- Essential joins and common filtering paths.
CREATE INDEX enrollment_offering_status_idx
    ON enrollment (offering_id, status, student_id);
CREATE INDEX enrollment_student_idx
    ON enrollment (student_id, status, offering_id);
CREATE INDEX assessment_result_enrollment_idx
    ON assessment_result (enrollment_id, assessment_id);
CREATE INDEX course_offering_term_course_idx
    ON course_offering (term_id, course_id);

-- GPA-like weighted average on a 5-point scale. This example treats a total
-- percentage score >= 70 as 5 points, >= 60 as 4, >= 50 as 3, >= 45 as 2,
-- >= 40 as 1, otherwise 0. Confirm the institution's real grading policy
-- before using these illustrative thresholds for any actual student record.
CREATE VIEW student_term_results AS
WITH weighted_totals AS (
    SELECT e.student_id,
           o.term_id,
           c.course_code,
           c.title,
           c.credits,
           ROUND(SUM(ar.score / a.max_score * a.weight_percent), 2) AS total_percent,
           SUM(a.weight_percent) AS recorded_weight_percent
    FROM enrollment e
    JOIN course_offering o ON o.offering_id = e.offering_id
    JOIN course c ON c.course_id = o.course_id
    JOIN assessment a ON a.offering_id = o.offering_id
    JOIN assessment_result ar
      ON ar.assessment_id = a.assessment_id
     AND ar.enrollment_id = e.enrollment_id
    WHERE e.status = 'completed'
    GROUP BY e.student_id, o.term_id, c.course_code, c.title, c.credits
)
SELECT *,
       CASE
         WHEN recorded_weight_percent < 100 THEN NULL
         WHEN total_percent >= 70 THEN 5
         WHEN total_percent >= 60 THEN 4
         WHEN total_percent >= 50 THEN 3
         WHEN total_percent >= 45 THEN 2
         WHEN total_percent >= 40 THEN 1
         ELSE 0
       END AS illustrative_grade_point
FROM weighted_totals;
